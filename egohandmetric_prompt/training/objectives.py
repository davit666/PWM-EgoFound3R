"""Masked native-H objectives. Unknown paper hyperparameters are explicit arguments.

Targets use camera coordinates in metres and the released 21/195 point order.
No loss operates on detached inference exports or interpolated R-rate tensors.
"""
from __future__ import annotations

import torch
from torch.nn import functional as F


def select(pred, target, valid):
    if pred.shape != target.shape or valid.shape != target.shape:
        raise ValueError("prediction, target and mask shapes must match")
    if valid.dtype != torch.bool:
        raise TypeError("supervision masks must be boolean")
    mask = valid & torch.isfinite(target)
    if not torch.isfinite(pred[mask]).all():
        raise FloatingPointError("nonfinite prediction on supervised elements")
    return pred[mask].float(), target[mask].float()


def masked_loss(pred, target, valid, kind="l1"):
    p, t = select(pred, target, valid)
    if p.numel() == 0:
        return None
    if kind == "bce":
        if ((t < 0) | (t > 1)).any():
            raise ValueError("binary targets must be in [0,1]")
        return F.binary_cross_entropy_with_logits(p, t)
    if kind == "smooth_l1":
        return F.smooth_l1_loss(p, t)
    if kind != "l1":
        raise ValueError(kind)
    return F.l1_loss(p, t)


def geometry_loss(pred, target, valid, log_conf, alpha):
    """Eq. 3 with mean root-relative point norm as the declared scale estimator."""
    if pred.shape != target.shape or valid.shape != pred.shape[:-1]:
        raise ValueError("geometry requires matching [...,N,3] and [...,N] mask")
    mask = valid & torch.isfinite(target).all(-1)
    if not mask.any():
        return None
    if not torch.isfinite(pred[mask]).all() or not torch.isfinite(log_conf[mask]).all():
        raise FloatingPointError("nonfinite geometry or confidence")
    p = torch.where(mask[..., None], pred.float(), 0)
    t = torch.where(mask[..., None], target.float(), 0)
    count = mask.sum(-1, keepdim=True).clamp_min(1)
    a_pred = (p.norm(dim=-1).sum(-1, keepdim=True) / count).clamp_min(1e-6)
    a_gt = (t.norm(dim=-1).sum(-1, keepdim=True) / count).clamp_min(1e-6)
    error = (p / a_pred[..., None] - t / a_gt[..., None]).abs().sum(-1)[mask]
    s = log_conf.float()[mask]
    return (s.exp() * error - alpha * s).mean()


def contact_loss(pred, target, valid, log_conf, alpha):
    p, t = select(pred, target, valid)
    if not p.numel():
        return None
    if ((t < 0) | (t > 1)).any():
        raise ValueError("contact targets must be in [0,1]")
    c = log_conf.float()[valid & torch.isfinite(target)]
    if not torch.isfinite(c).all():
        raise FloatingPointError("nonfinite contact confidence")
    return (c.exp() * F.binary_cross_entropy_with_logits(p, t, reduction="none") - alpha * c).mean()


def objective(outputs, targets, weights, *, confidence_alpha, heatmap_positive_weight=1.):
    """Targets are {name: (tensor, bool_mask)}; weights must cover all active terms.

    Direct heatmap/offset targets must be generated by a versioned adapter.
    Scene depth/camera target preparation is intentionally not inferred here.
    """
    losses = {}
    for side in ("joint", "vertex"):
        key = f"{side}_offset"
        if key in targets:
            t, m = targets[key]
            losses[key] = geometry_loss(outputs[f"dense_{key}"], t, m,
                                       outputs[f"dense_{side}_log_conf"], confidence_alpha)
        for attr in ("visibility", "contact", "distance"):
            key = f"{side}_{attr}"
            if key not in targets:
                continue
            t, m = targets[key]
            if attr == "contact":
                losses[key] = contact_loss(outputs[f"dense_{side}_contact_logits"], t, m,
                                          outputs[f"dense_{side}_contact_log_conf"], confidence_alpha)
            elif attr == "visibility":
                losses[key] = masked_loss(outputs[f"dense_{side}_visibility_logits"], t, m, "bce")
            else:
                if (t[m & torch.isfinite(t)] < 0).any():
                    raise ValueError("distances must be nonnegative metres")
                # Sanitize before log: invalid NaNs must not enter autograd.
                m = m & torch.isfinite(t)
                t = torch.where(m, t, 0)
                losses[key] = masked_loss(outputs[f"dense_{side}_contact_log_distance"],
                                          torch.log1p(1000 * t), m, "smooth_l1")
    direct = {"heatmap": ("keypoint_heatmap_logits", "bce"),
              "offset2d": ("keypoint_offset", "smooth_l1"),
              "in_view": ("hand_in_view_logits", "bce"),
              "log_metric": ("log_metric_value", "smooth_l1")}
    for key, (source, kind) in direct.items():
        if key in targets:
            t, m = targets[key]
            p = outputs[source]
            if key == "offset2d":
                p = 1.5 * torch.tanh(p.float())
            if key == "heatmap":
                pp, tt = select(p, t, m)
                losses[key] = F.binary_cross_entropy_with_logits(
                    pp, tt, pos_weight=pp.new_tensor(heatmap_positive_weight)) if pp.numel() else None
            else:
                losses[key] = masked_loss(p, t, m, kind)
    if "reprojection" in targets:
        uv, valid = targets["reprojection"]
        if "projection_K" not in targets:
            raise ValueError("reprojection requires prepared camera intrinsics")
        K, kmask = targets["projection_K"]
        xyz = outputs["dense_joint_xyz"].float()
        kvalid = kmask.all(dim=(-2,-1)) & torch.isfinite(K).all(dim=(-2,-1))
        K = torch.where(kvalid[..., None, None], K, torch.eye(3, device=K.device))
        pixel = torch.einsum("btij,btsnj->btsni", K.float(), xyz)
        projection = pixel[..., :2] / pixel[..., 2:].clamp_min(1e-6)
        valid = valid & (xyz[..., 2:] > 1e-6) & kvalid[...,None,None,None]
        losses["reprojection"] = masked_loss(projection, uv, valid)
        losses["projection_K"] = None  # conditioning metadata, never a loss
    if any(k.startswith("scene_") for k in targets):
        from .scene import scene_losses
        losses.update(scene_losses(outputs, targets, confidence_alpha))
    unknown = set(targets) - set(losses) - {"scene_pose"}
    if unknown:
        raise ValueError(f"unimplemented target objectives: {sorted(unknown)}")
    losses = {k: v for k, v in losses.items() if v is not None}
    if not losses:
        raise ValueError("batch has no supervised targets")
    if set(losses) - set(weights):
        raise ValueError("explicit weight required for every active objective")
    total = sum(weights[k] * v for k, v in losses.items())
    if not torch.isfinite(total):
        raise FloatingPointError("nonfinite total loss")
    return total, losses
